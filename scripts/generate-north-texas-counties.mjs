// Generates src/lib/north-texas-counties.ts: county outlines around Tarrant
// County for the hero's solar cycle map.
//
// Source: U.S. Census Bureau cartographic boundary files, published as
// TopoJSON by us-atlas. Run with `node scripts/generate-north-texas-counties.mjs`.

import { writeFile } from "node:fs/promises";

const SOURCE = "https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/counties-10m.json";
const OUTPUT = new URL("../src/lib/north-texas-counties.ts", import.meta.url);
const TEXAS = "48";
const TARRANT = "48439";
/** Keep counties whose center is within this many miles of Tarrant's. */
const RADIUS_MILES = 62;

const topology = await (await fetch(SOURCE)).json();
const { scale, translate } = topology.transform;

// Arcs are quantized and delta-encoded.
const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

const arcPoints = (index) => (index < 0 ? [...arcs[~index]].reverse() : arcs[index]);
const ringPoints = (ring) => ring.flatMap((index, i) => arcPoints(index).slice(i ? 1 : 0));
const polygons = (geometry) => (geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs);

// Area-weighted centroid of a county's largest outer ring.
function centroid(rings) {
  let best = { area: 0, x: 0, y: 0 };
  for (const ring of rings) {
    let area = 0;
    let cx = 0;
    let cy = 0;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const cross = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
      area += cross;
      cx += (ring[j][0] + ring[i][0]) * cross;
      cy += (ring[j][1] + ring[i][1]) * cross;
    }
    if (Math.abs(area) > Math.abs(best.area)) best = { area, x: cx / (3 * area), y: cy / (3 * area) };
  }
  return [best.x, best.y];
}

const texas = topology.objects.counties.geometries
  .filter((g) => String(g.id).startsWith(TEXAS))
  .map((g) => {
    const outer = polygons(g).map((polygon) => ringPoints(polygon[0]));
    return { geometry: g, outer, center: centroid(outer) };
  });

const tarrant = texas.find((c) => c.geometry.id === TARRANT);
const [lng0, lat0] = tarrant.center;
const miles = ([lng, lat]) => Math.hypot((lng - lng0) * 69 * Math.cos((lat0 * Math.PI) / 180), (lat - lat0) * 69);
const selected = texas.filter((c) => miles(c.center) <= RADIUS_MILES).sort((a, b) => miles(a.center) - miles(b.center));

const round = (n) => Math.round(n * 1e4) / 1e4;
const point = ([lng, lat]) => [round(lng), round(lat)];

const counties = selected.map(({ geometry, center }) => ({
  fips: String(geometry.id),
  name: geometry.properties.name,
  center: point(center),
  rings: polygons(geometry).flatMap((polygon) => polygon.map((ring) => ringPoints(ring).map(point))),
}));

// Each border once, so adjoining counties don't draw a shared edge twice.
const borderArcs = new Set(
  selected.flatMap(({ geometry }) => polygons(geometry).flat(2).map((index) => (index < 0 ? ~index : index))),
);
const borders = [...borderArcs].sort((a, b) => a - b).map((index) => arcs[index].map(point));

const source = `// Generated by scripts/generate-north-texas-counties.mjs. Do not edit by hand.
// Source: U.S. Census Bureau cartographic boundary files, via
// us-atlas@3.0.1 (counties-10m). Coordinates are [lng, lat].

export interface County {
  fips: string;
  name: string;
  /** Area-weighted center of the county's largest outline. */
  center: [number, number];
  rings: [number, number][][];
}

export const TARRANT_FIPS = "${TARRANT}";

export const COUNTIES: County[] = [
${counties.map((c) => `  ${JSON.stringify(c)},`).join("\n")}
];

/** Every county border once, including the region's outer edge. */
export const BORDERS: [number, number][][] = [
${borders.map((b) => `  ${JSON.stringify(b)},`).join("\n")}
];
`;

await writeFile(OUTPUT, source);
console.log(`Wrote ${counties.length} counties (${counties.map((c) => c.name).join(", ")}) and ${borders.length} borders.`);
